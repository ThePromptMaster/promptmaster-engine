/** A key as the dictionaries hold it. */
export type MessageId = keyof typeof en;
type PluralBase<K> = K extends `${infer B}_one` ? B : never;
/** A key as `t()` takes it: any message, or a plural pair's base with `{ count }`. */
export type MessageKey = MessageId | PluralBase<MessageId>;
export type Messages = Record<MessageId, string>;
